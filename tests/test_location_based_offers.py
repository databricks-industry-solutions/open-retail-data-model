"""Tests for the Location-Based Offers use case (promote-with-purpose).

Static contract tests (no engine) keep the DDL, the generator and the enum
domains in relationships.sql mutually consistent. Engine tests run the *real*
gold SQL on Spark over temp-view fixtures — the four funnel rates, the grain PK,
and the durable-zone_id rollup that the SCD2-JOIN contract requires.

The offer tables are generated by trade_promotion.py, not by a module of their
own: _registry.py permits exactly one provider per schema key and that generator
already provides `promo`.
"""

import ast
import datetime
import os
import random
import re

import pytest
import sqlglot
import sqlglot.expressions as E

from tools.ordm_config import resolve

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PKG = os.path.join(REPO, "outcome-packages", "promote-with-purpose")
GENERATOR = os.path.join(REPO, "runtime", "synthetic-data", "generators", "trade_promotion.py")
RELATIONSHIPS = os.path.join(PKG, "relationships.sql")
GOLD_PERF = os.path.join(PKG, "gold", "gold_location_offer_performance.sql")
GOLD_ZONE = os.path.join(PKG, "gold", "gold_zone_engagement_weekly.sql")

# table -> (ddl path, surrogate key, generator *_COLUMNS constant)
TABLES = {
    "offer_zone": ("outcome-packages/promote-with-purpose/tables/offer_zone.sql",
                   "zone_sk", "OFFER_ZONE_COLUMNS"),
    "location_offer": ("outcome-packages/promote-with-purpose/tables/location_offer.sql",
                       "location_offer_sk", "LOCATION_OFFER_COLUMNS"),
    "offer_event": ("outcome-packages/promote-with-purpose/tables/offer_event.sql",
                    "offer_event_sk", "OFFER_EVENT_COLUMNS"),
}

# generator constant -> (table, column) whose enum domain relationships.sql enforces
ENUM_CONST_TO_COLUMN = {
    "ZONE_TYPES": "zone_type",
    "TRIGGER_TYPES": "trigger_type",
    "OFFER_CHANNELS": "channel",
    "OFFER_STATUSES": "status",
    "OFFER_EVENT_TYPES": "event_type",
    "SUPPRESSION_REASONS": "suppression_reason",
}

# No coordinate, device identifier or location trail may reach the event log.
FORBIDDEN_COLUMN = re.compile(r"lat|lon|coord|device|imei|idfa|maid|geohash", re.I)
GEOHASH_ALPHABET = "0123456789bcdefghjkmnpqrstuvwxyz"


# ---------- helpers ----------

def _detok(text):
    # Resolve ${catalog}/${*_schema} to real identifiers via the shared resolver.
    return resolve(text, "ordm")


def _ddl(table):
    return _detok(open(os.path.join(REPO, TABLES[table][0])).read())


def _ddl_columns(table):
    create = next(s for s in sqlglot.parse(_ddl(table), read="databricks", error_level="ignore")
                  if isinstance(s, E.Create))
    sk = TABLES[table][1]
    return [c.name for c in create.find_all(E.ColumnDef) if c.name != sk]


def _generator_constants():
    mod = ast.parse(open(GENERATOR).read())
    out = {}
    for node in mod.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) \
                and isinstance(node.value, ast.List) \
                and all(isinstance(e, ast.Constant) for e in node.value.elts):
            out[node.targets[0].id] = [e.value for e in node.value.elts]
    return out


def _enforced_enum(column):
    """The value set an ENFORCED Delta CHECK constraint pins `column` to."""
    text = open(RELATIONSHIPS).read()
    m = re.search(rf"\b{column}\s+IN\s*\(([^)]*)\)", text)
    assert m, f"relationships.sql has no enforced IN (...) domain for {column}"
    return {v.strip().strip("'") for v in m.group(1).split(",")}


def _insert_select_body(path, table_map):
    """Return the SELECT body of a `CREATE TABLE … ; INSERT OVERWRITE <fqtn> <body>;`
    gold file, with UC names rewritten to fixture temp views.

    tools.ordm_config.view_select_body handles `CREATE … VIEW … AS` only; both LBO
    gold objects are materialized as a TABLE plus an INSERT OVERWRITE so the grain
    PK can be declared, which that helper raises on.
    """
    raw = open(path).read()
    # Anchored to column 0: the header prose describes the statement ("an INSERT
    # OVERWRITE that loads it"), and an unanchored match lands in the comment.
    m = re.search(r"^INSERT\s+OVERWRITE\s+\S+", raw, re.M)
    assert m, f"{os.path.basename(path)} has no INSERT OVERWRITE statement"
    body = raw[m.end():].strip().rstrip(";").rstrip()
    for fq, view in table_map.items():
        body = body.replace(fq, view)
    return body


def _generated_offer_event_rows(offers, seed=2002, max_per_offer=400):
    """Run the real row builder without requiring a Spark action.

    The generator builds these bounded demo rows on the driver before handing
    them to Spark, so a capture double lets this regression inspect the exact
    emitted journeys while keeping the static test gate fast.
    """
    tree = ast.parse(open(GENERATOR).read())
    wanted = [
        node for node in tree.body
        if (isinstance(node, ast.Assign)
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id in {"ULID_ALPHABET", "SUPPRESSION_REASONS"})
        or (isinstance(node, ast.FunctionDef)
            and node.name in {"_ulid", "build_offer_events"})
    ]

    class _Functions:
        @staticmethod
        def current_timestamp():
            return None

        @staticmethod
        def lit(_value):
            return None

    class _Types:
        @staticmethod
        def StructType(fields):
            return fields

        @staticmethod
        def StructField(*args):
            return args

        @staticmethod
        def StringType():
            return "string"

        @staticmethod
        def LongType():
            return "long"

        @staticmethod
        def TimestampType():
            return "timestamp"

        @staticmethod
        def BooleanType():
            return "boolean"

    class _Frame:
        def withColumn(self, _name, _value):
            return self

    class _Spark:
        rows = None

        def createDataFrame(self, rows, _schema):
            self.rows = rows
            return _Frame()

    namespace = {
        "datetime": datetime,
        "random": random,
        "T": _Types,
        "F": _Functions,
        "RECORD_SOURCE": "synthetic",
    }
    exec(compile(ast.Module(body=wanted, type_ignores=[]), GENERATOR, "exec"), namespace)
    capture = _Spark()
    namespace["build_offer_events"](
        capture,
        offers,
        [f"CUST-{i:08d}" for i in range(500)],
        [f"SALE-{i:08d}" for i in range(100)],
        seed,
        max_per_offer,
    )
    return capture.rows


# ---------- static: DDL / generator / enums ----------

@pytest.mark.parametrize("table", list(TABLES))
def test_ddl_parses_as_create(table):
    create = next((s for s in sqlglot.parse(_ddl(table), read="databricks", error_level="ignore")
                   if isinstance(s, E.Create)), None)
    assert create is not None, f"{table} did not parse as CREATE TABLE"


@pytest.mark.parametrize("table", list(TABLES))
def test_generator_columns_match_ddl(table):
    # Order matters: _write selects positionally against the DDL column list.
    gen = _generator_constants()[TABLES[table][2]]
    ddl = _ddl_columns(table)
    assert gen == ddl, f"{table} drift — generator={gen} ddl={ddl}"


@pytest.mark.parametrize("const", list(ENUM_CONST_TO_COLUMN))
def test_generator_enum_within_enforced_domain(const):
    gen = set(_generator_constants()[const])
    enforced = _enforced_enum(ENUM_CONST_TO_COLUMN[const])
    assert gen <= enforced, \
        f"{const}: generator emits {sorted(gen - enforced)} outside the enforced CHECK domain"


def test_pk_contract_on_offer_event():
    # PR 2's contract: surrogate *_sk is the PK, *_id is the durable business key.
    cols = _ddl_columns("offer_event")
    assert cols[0] == "offer_event_id", "offer_event_id must be the durable business key"
    assert "offer_event_sk" not in cols, "offer_event_sk is the IDENTITY PK, not a generator column"


def test_centroid_geohash_is_seven_geohash_chars():
    import sys
    sys.path.insert(0, os.path.join(REPO, "runtime", "synthetic-data", "generators"))
    mod = ast.parse(open(GENERATOR).read())
    fn = next(n for n in mod.body
              if isinstance(n, ast.FunctionDef) and n.name == "_geohash7")
    src = ast.unparse(fn)
    assert "GEOHASH_ALPHABET" in src, "_geohash7 must draw from the geohash alphabet"
    assert "range(7)" in src, "_geohash7 must emit exactly 7 characters"
    alphabet = next(n.value.value for n in mod.body
                    if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)
                    and n.targets[0].id == "GEOHASH_ALPHABET")
    assert alphabet == GEOHASH_ALPHABET, "geohash alphabet drifted from the standard set"


