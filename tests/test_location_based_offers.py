def test_seeded_generator_orders_driver_rows_before_collect():
    """Spark partition order must not decide how the seeded RNG is consumed."""
    tree = ast.parse(open(GENERATOR).read())
    generate = next(
        node for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name == "generate"
    )
    collects = [
        node for node in ast.walk(generate)
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "collect"
    ]
    unordered = [
        node.lineno for node in collects
        if not any(
            isinstance(child, ast.Attribute) and child.attr == "orderBy"
            for child in ast.walk(node.func.value)
        )
    ]
    assert collects
    assert not unordered, f"seed inputs collected without orderBy at lines {unordered}"


def test_generated_funnel_journeys_do_not_cross_fiscal_weeks():
    """Weekly gold denominators must contain the children of each delivery."""
    start = datetime.datetime(2024, 1, 7)
    rows = _generated_offer_event_rows(
        [{
            "location_offer_sk": 1,
            "offer_start_ts": start,
            "offer_end_ts": start + datetime.timedelta(days=75),
            "zone_store_id": "STR-00001",
        }]
    )

    journeys = []
    for row in rows:
        if row[5] == "triggered":
            journeys.append([row])
        else:
            journeys[-1].append(row)

    assert journeys
    for journey in journeys:
        timestamps = [row[4] for row in journey]
        fiscal_week_starts = {
            ts.date() - datetime.timedelta(days=(ts.weekday() + 1) % 7)
            for ts in timestamps
        }
        assert len(fiscal_week_starts) == 1, \
            "a funnel journey crossed the Sunday-start fiscal-week boundary"
        assert timestamps == sorted(timestamps), "funnel events are not time-ordered"

    event_types = _generator_constants()["OFFER_EVENT_TYPES"]
    weekly_counts = {}
    for row in rows:
        event_ts = row[4]
        week_start = event_ts.date() - datetime.timedelta(
            days=(event_ts.weekday() + 1) % 7
        )
        key = (row[1], row[3], week_start)
        empty_counts = {event_type: 0 for event_type in event_types}
        counts = weekly_counts.setdefault(key, empty_counts)
        counts[row[5]] += 1

    for counts in weekly_counts.values():
        assert counts["delivered"] + counts["suppressed"] == counts["triggered"]
        assert counts["opened"] <= counts["delivered"]
        assert counts["redeemed"] <= counts["delivered"]


# ---------- engine: the real gold SQL over temp-view fixtures ----------

_PERF_VIEWS = {
    "${catalog}.${promo_schema}.offer_event": "offer_event",
    "${catalog}.${calendar_schema}.fiscal_calendar": "fiscal_calendar",
    "${catalog}.${transaction_schema}.sales": "sales",
}
_ZONE_VIEWS = {
    "${catalog}.${promo_schema}.offer_event": "offer_event",
    "${catalog}.${promo_schema}.location_offer": "location_offer",
    "${catalog}.${promo_schema}.offer_zone": "offer_zone",
    "${catalog}.${calendar_schema}.fiscal_calendar": "fiscal_calendar",
}
_WEEK = datetime.date(2024, 1, 7)


def _ts(day, hour=9):
    return datetime.datetime.combine(_WEEK + datetime.timedelta(days=day),
                                     datetime.time(hour, 0))


def _build(spark):
    spark.createDataFrame(
        [(_WEEK + datetime.timedelta(days=d), 202401) for d in range(7)],
        "date_key date, fiscal_week_id int",
    ).createOrReplaceTempView("fiscal_calendar")

    # ONE durable zone with TWO SCD2 versions — the rollup must not fragment.
    spark.createDataFrame(
        [(1, "Z1"), (2, "Z1")], "zone_sk bigint, zone_id string",
    ).createOrReplaceTempView("offer_zone")

    # One offer per zone version, both resolving to the same durable zone_id.
    spark.createDataFrame(
        [(10, 1, "active"), (20, 2, "active")],
        "location_offer_sk bigint, zone_sk bigint, status string",
    ).createOrReplaceTempView("location_offer")

    spark.createDataFrame(
        [("SAL-1", 42.50)], "sales_id string, net_revenue double",
    ).createOrReplaceTempView("sales")

    # Offer 10: 10 triggered, 2 suppressed, 8 delivered, 3 opened, 1 redeemed.
    #   delivery 0.8 · open 0.375 · redemption 0.125 · suppression 0.2
    rows = []
    for i in range(10):
        rows.append(("E-T%d" % i, 10, "C%d" % i, "S1", _ts(1), "triggered", None))
    for i in range(2):
        rows.append(("E-S%d" % i, 10, "C%d" % i, "S1", _ts(1, 10), "suppressed", None))
    for i in range(8):
        rows.append(("E-D%d" % i, 10, "C%d" % i, "S1", _ts(1, 11), "delivered", None))
    for i in range(3):
        rows.append(("E-O%d" % i, 10, "C%d" % i, "S1", _ts(1, 12), "opened", None))
    rows.append(("E-R0", 10, "C0", "S1", _ts(1, 13), "redeemed", "SAL-1"))
    # Offer 20 sits on the OTHER zone version, same durable zone, same week.
    for i in range(4):
        rows.append(("E-T2%d" % i, 20, "C%d" % i, "S2", _ts(2), "triggered", None))
    for i in range(4):
        rows.append(("E-D2%d" % i, 20, "C%d" % i, "S2", _ts(2, 11), "delivered", None))

    spark.createDataFrame(
        rows,
        "offer_event_id string, location_offer_sk bigint, customer_id string, "
        "store_id string, event_ts timestamp, event_type string, transaction_id string",
    ).createOrReplaceTempView("offer_event")

    spark.sql("CREATE OR REPLACE TEMP VIEW gold_perf AS "
              + _insert_select_body(GOLD_PERF, _PERF_VIEWS))
    spark.sql("CREATE OR REPLACE TEMP VIEW gold_zone AS "
              + _insert_select_body(GOLD_ZONE, _ZONE_VIEWS))


def test_gold_performance_returns_rows(spark):
    _build(spark)
    assert spark.sql("SELECT COUNT(*) AS n FROM gold_perf").first().n > 0


def test_gold_performance_rates_are_bounded(spark):
    # The invariant gold_location_offer_performance_rate_bounds asserts in DQ.
    _build(spark)
    bad = spark.sql("""
        SELECT * FROM gold_perf
        WHERE delivery_rate    < 0 OR delivery_rate    > 1
           OR open_rate        < 0 OR open_rate        > 1
           OR redemption_rate  < 0 OR redemption_rate  > 1
           OR suppression_rate < 0 OR suppression_rate > 1
    """).count()
    assert bad == 0, "a funnel rate fell outside [0, 1]"


def test_gold_performance_rates_match_the_funnel(spark):
    _build(spark)
    row = spark.sql("SELECT * FROM gold_perf WHERE location_offer_sk = 10").first()
    assert row.trigger_events == 10 and row.suppressed_events == 2
    assert row.delivered_events == 8 and row.opened_events == 3 and row.redemptions == 1
    assert abs(float(row.delivery_rate) - 0.8) < 1e-6
    assert abs(float(row.open_rate) - 0.375) < 1e-6
    assert abs(float(row.redemption_rate) - 0.125) < 1e-6
    assert abs(float(row.suppression_rate) - 0.2) < 1e-6
    assert abs(float(row.attributed_sales_amount) - 42.50) < 1e-6


def test_gold_performance_grain_pk_is_unique(spark):
    _build(spark)
    dupes = spark.sql("""
        SELECT location_offer_sk, store_id, fiscal_week_id
        FROM gold_perf
        GROUP BY location_offer_sk, store_id, fiscal_week_id
        HAVING COUNT(*) > 1
    """).count()
    assert dupes == 0, "gold_location_offer_performance grain PK is not unique"


def test_gold_zone_is_keyed_on_durable_zone_id(spark):
    # Two SCD2 versions of Z1 must collapse into ONE zone_id x week row
    # (standard §A.16: never aggregate on a version-specific _sk).
    _build(spark)
    rows = spark.sql("SELECT zone_id, fiscal_week_id, trigger_events "
                     "FROM gold_zone").collect()
    assert len(rows) == 1, f"expected one durable zone-week row, got {len(rows)}"
    assert rows[0].zone_id == "Z1"
    assert rows[0].trigger_events == 14, "events from both zone versions must roll up"


def test_gold_zone_grain_pk_is_unique(spark):
    _build(spark)
    dupes = spark.sql("""
        SELECT zone_id, fiscal_week_id FROM gold_zone
        GROUP BY zone_id, fiscal_week_id HAVING COUNT(*) > 1
    """).count()
    assert dupes == 0, "gold_zone_engagement_weekly grain PK is not unique"


def test_gold_zone_conversion_rate_is_bounded(spark):
    _build(spark)
    bad = spark.sql("SELECT * FROM gold_zone "
                    "WHERE conversion_rate < 0 OR conversion_rate > 1").count()
    assert bad == 0, "zone conversion_rate fell outside [0, 1]"
