#!/usr/bin/env python3
"""Generate the conformance matrix in the ORDM standard from standards/rules.yaml.

The matrix is the human-readable view of the rules registry. It is generated,
not hand-maintained, so it cannot drift from the registry. tests/standards/
test_standards_meta.py asserts the block in the standard matches what this
renders; this script can also write it back.

Usage:
  python tools/gen_conformance_matrix.py --check   # exit 1 if the doc is stale
  python tools/gen_conformance_matrix.py --write   # regenerate the block in the doc
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
RULES_PATH = REPO_ROOT / "standards" / "rules.yaml"
STANDARD_PATH = REPO_ROOT / "docs" / "data-model-standards.md"

START = "<!-- CONFORMANCE-MATRIX:START (generated by tools/gen_conformance_matrix.py; do not edit by hand) -->"
END = "<!-- CONFORMANCE-MATRIX:END -->"


def load_rules() -> dict:
    return yaml.safe_load(RULES_PATH.read_text())


def render_matrix(data: dict) -> str:
    """Render the matrix block (between, not including, the markers)."""
    rules = sorted(data.get("rules", []), key=lambda r: (r.get("status") != "enforced", r["id"]))
    lines = [
        "| Rule ID | Title | Section | Layer | Severity | Status | Enforced by |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rules:
        test = r.get("test", "")
        enforced_by = f"`{test.split('::')[-1]}`" if test else "-"
        lines.append(
            f"| `{r['id']}` | {r['title']} | {r.get('standard_section','')} | "
            f"{r.get('layer','')} | {r.get('severity','')} | {r.get('status','')} | {enforced_by} |"
        )
    exceptions = data.get("known_exceptions") or []
    lines.append("")
    if exceptions:
        lines.append(f"Tracked exceptions (excused until fixed): {len(exceptions)}.")
        for e in exceptions:
            when = e.get("remove_when")
            suffix = f" ({when})" if when else ""
            lines.append(f"- `{e['rule']}`: {e['match']}{suffix}")
    else:
        lines.append("Tracked exceptions: none.")
    return "\n".join(lines)


def _split_doc(text: str) -> tuple[str, str]:
    if START not in text or END not in text:
        raise SystemExit(
            f"Markers not found in {STANDARD_PATH}. Add:\n{START}\n{END}\nwhere the matrix should render."
        )
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    return before, after


def current_block(text: str) -> str:
    _, rest = text.split(START, 1)
    block, _ = rest.split(END, 1)
    return block.strip("\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the doc block is stale")
    ap.add_argument("--write", action="store_true", help="regenerate the block in the doc")
    args = ap.parse_args()

    data = load_rules()
    matrix = render_matrix(data)
    text = STANDARD_PATH.read_text()

    if args.write:
        before, after = _split_doc(text)
        STANDARD_PATH.write_text(f"{before}{START}\n\n{matrix}\n\n{END}{after}")
        print(f"Wrote conformance matrix to {STANDARD_PATH}")
        return 0

    if args.check:
        if current_block(text).strip() != matrix.strip():
            print("Conformance matrix in the standard is stale. Run: python tools/gen_conformance_matrix.py --write")
            return 1
        print("Conformance matrix is in sync.")
        return 0

    print(matrix)
    return 0


if __name__ == "__main__":
    sys.exit(main())
