BADGE_START = "<!-- STATUS-BADGE:START (generated by tools/gen_status.py; do not edit by hand) -->"
BADGE_END = "<!-- STATUS-BADGE:END -->"
CORE_START = "<!-- STATUS-CORE:START (generated by tools/gen_status.py; do not edit by hand) -->"
CORE_END = "<!-- STATUS-CORE:END -->"
OUTCOME_START = "<!-- STATUS-OUTCOMES:START (generated by tools/gen_status.py; do not edit by hand) -->"
OUTCOME_END = "<!-- STATUS-OUTCOMES:END -->"


def _emoji_of(cell: str) -> str:
    for e in KNOWN_EMOJI:
        if e in cell:
            return e
    return ""


def parse_status(text: str) -> dict[str, str]:
    """Map each STATUS.md row key (first column) -> its status emoji.

    Derived from parse_status_text, so the badge/tables and the per-folder status lines
    always read STATUS.md the same way.
    """
    return {key: _emoji_of(status) for key, status in parse_status_text(text).items()}


def parse_status_text(text: str) -> dict[str, str]:
    """Map each STATUS.md row key -> its full status text (emoji + description).

    E.g., "customer" -> "🟢 Review complete"
    """
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 2:
            continue
        key = cells[0]
        # skip header + separator rows
        if key.lower() in ("domain", "package") or set(key) <= set("-: "):
            continue
        status_cell = cells[1].strip()
        # Extract text up to any HTML comment (ignore trailing comments in STATUS.md)
        status_text = status_cell.split("<!--")[0].strip() if "<!--" in status_cell else status_cell
        if _emoji_of(status_text):
            out[key] = status_text
    return out


def render_badge(status: dict[str, str]) -> str:
    done = sum(1 for key, _ in CORE_LAYOUT if status.get(key) in DONE_EMOJI)
    total = len(CORE_LAYOUT)
    published = sum(1 for key, _ in CORE_LAYOUT if status.get(key) == "✅")
    label = "published" if published == total else "review--complete"
    url = (f"https://img.shields.io/badge/canonical_core-{done}%2F{total}_{label}-brightgreen")
    return f"[![Canonical core]({url})](STATUS.md)"


def domain_meta(model_path: Path = MODEL_PATH) -> dict[str, tuple[str, int]]:
    """Map each core domain -> (representative grain, table count), read from model.json.

    Grain is the most common table `role`, ties broken by GRAIN_PRIORITY, so the table
    carries information the Explorer hero already shows rather than a bare status list.
    """
    import json
    from collections import Counter
    out: dict[str, tuple[str, int]] = {}
    if not model_path.exists():
        return out
    model = json.loads(model_path.read_text())
    for u in model.get("units", []):
        if u.get("kind") != "core":
            continue
        tables = u.get("tables", [])
        counts = Counter(t.get("role") for t in tables if t.get("role"))
        grain = min(counts, key=lambda r: (-counts[r], GRAIN_PRIORITY.get(r, 9))) if counts else "-"
        out[u["name"]] = (grain, len(tables))
    return out


def render_core_table(status: dict[str, str], meta: dict | None = None) -> str:
    if meta is None:
        meta = domain_meta()
    lines = ["| Domain | Grain | Tables | Status |", "|---|:---:|:---:|:---:|"]
    for key, name in CORE_LAYOUT:
        grain, ntables = meta.get(key, ("-", "-"))
        lines.append(f"| [{name}](canonical-core/{key}/) | {grain} | {ntables} | {status.get(key, '⚪')} |")
    return "\n".join(lines)


def outcome_use_cases(model_path: Path = MODEL_PATH) -> dict[str, tuple[int, int, int, list[str]]]:
    """Map each outcome package key -> (done, in_progress, total, done_names) use cases.

    Read from model.json (the package's DECLARED intent, from its use-cases.yaml folded in),
    so `done/total` is the one completeness signal with a real denominator - distinct from the
    build Status, which only says whether tables/artifacts exist, not whether the package has
    "all the tables it needs" (there is no such target, by design). `done_names` lets the
    README name the delivered use cases rather than only counting them.
    """
    import json
    out: dict[str, tuple[int, int, int, list[str]]] = {}
    if not model_path.exists():
        return out
    model = json.loads(model_path.read_text())
    for u in model.get("units", []):
        if u.get("kind") != "outcome":
            continue
        ucs = u.get("use_cases", []) or []
        # `done` counts by STATUS (robust to a use case that is status:done but unnamed);
        # `done_names` is only the display subset, so a nameless done still counts toward
        # done/total even though it can't be listed by name.
        done = sum(1 for c in ucs if c.get("status") == "done")
        done_names = [c.get("name") for c in ucs if c.get("status") == "done" and c.get("name")]
        in_progress = sum(1 for c in ucs if c.get("status") == "in-progress")
        out[u["name"]] = (done, in_progress, len(ucs), done_names)
    return out


def _md_cell_safe(s: str) -> str:
    """Make a string safe to drop inside a markdown table cell: escape the column
    delimiter and flatten any newline so a stray `|` or line break in a use-case
    name can't silently break the generated table's structure."""
    return s.replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def _uc_cell(done: int, in_progress: int, total: int, done_names: list[str] | None = None) -> str:
    if total == 0:
        return "—"
    # Name the delivered use cases, not just the count, so the grid reads as "what shipped".
    if done and done_names:
        names = ", ".join(_md_cell_safe(n) for n in done_names)
        cell = f"{done}/{total} done: {names}"
    else:
        cell = f"{done}/{total} done"
    if in_progress:
        cell += f" · {in_progress} in progress"
    return cell


def render_outcome_tables(status: dict[str, str], uc: dict | None = None) -> str:
    if uc is None:
        uc = outcome_use_cases()
    # Two distinct axes, labelled so "Status" is not read as "complete": build state vs
    # declared-outcome delivery. See docs/definition-of-done.md (Done% grades artifacts,
    # not model completeness) and ADR 0013 (use cases are a separate planning tier).
    caption = ("_Two axes: **Status** = artifacts built and reviewed (from `STATUS.md`); "
               "**Use cases** = `done / all declared` business outcomes for the package "
               "(from its `use-cases.yaml`), naming the delivered ones, with an in-progress "
               "count where relevant; the remainder are planned or blocked. A package can be "
               "built without every use case done, and vice versa._")
    blocks: list[str] = [caption]
    for theme, rows in OUTCOME_LAYOUT:
        block = [f"**{theme}**", "", "| Status | Package | Use cases |", "|:---:|---|---|"]
        for key, name, annotation in rows:
            d, ip, tot, done_names = uc.get(key, (0, 0, 0, []))
            block.append(
                f"| {status.get(key, '⚪')} | [{name}](outcome-packages/{key}/){annotation} "
                f"| {_uc_cell(d, ip, tot, done_names)} |"
            )
        blocks.append("\n".join(block))
    return "\n\n".join(blocks)


def _replace_block(text: str, start: str, end: str, block: str, pad: bool = True) -> str:
    if start not in text or end not in text:
        raise SystemExit(f"Markers not found in {README_PATH}:\n{start}\n{end}")
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    # Tables need a blank line around them to render; a badge should stay on the
    # same paragraph as its neighbours so the badges form one row (pad=False).
    sep = "\n\n" if pad else "\n"
    return f"{before}{start}{sep}{block}{sep}{end}{after}"


def _current_block(text: str, start: str, end: str) -> str:
    _, rest = text.split(start, 1)
    block, _ = rest.split(end, 1)
    return block.strip("\n")


def _extract_generic_suffix(line: str) -> str:
    """Extract the non-status suffix segments worth keeping from a status line.

    Preserves "· Last reviewed: YYYY-MM-DD" and "· Marketplace listing: <state>" (separate
    axes STATUS.md does not carry); drops everything else. Returns "" when none match.
    """
    # A listing state runs to the next " · " segment or the end of the line, so a
    # multi-word state ("in review") is kept whole rather than cut at its first word.
    keep = re.findall(
        r"· (?:Last reviewed: \d{4}-\d{2}-\d{2}|Marketplace listing: [^·\n]+?(?=\s*(?:·|$)))",
        line,
    )
    return " ".join(keep)


def _generate_status_line(domain_or_package: str, status_text: dict[str, str]) -> str:
    """Generate a status line for a domain or outcome package.

    Args:
        domain_or_package: key like "customer" or "unified-customer-view"
        status_text: dict from parse_status_text

    Returns:
        The full "> Status: ..." line, or empty string if not found.
    """
    if domain_or_package not in status_text:
        return ""
    text = status_text[domain_or_package]
    return f"> Status: {text} ({MODEL_VERSION})"


def _scan_header(lines: list[str]) -> tuple[list[int], int | None]:
    """Indices of the header's "> Status:" lines, and of its "# " title line.

    The header is everything before the first "## " section heading. The single scanner
    shared by --write and --check: only header status lines outside ``` code fences count,
    so a fenced example, or a "> Status:" callout in a body section, is never counted
    (--check) or rewritten or removed (--write).
    """
    in_code_fence = False
    status_indices: list[int] = []
    title_index = None
    for i, line in enumerate(lines):
        stripped = line.lstrip()
        if stripped.startswith("```"):
            in_code_fence = not in_code_fence
        elif not in_code_fence:
            if stripped.startswith("## "):
                break
            if stripped.startswith("> Status:"):
                status_indices.append(i)
            elif stripped.startswith("#") and not stripped.startswith("##") and title_index is None:
                title_index = i
    return status_indices, title_index


def _update_status_line_in_file(file_path: Path, domain_or_package: str,
                                 status_text: dict[str, str]) -> bool:
    """Replace or insert the header's "> Status:" line in a file.

    Only the header (before the first "## " section, outside code fences) is scanned; see
    _scan_header. If it has a status line, replaces it and drops any later header duplicates
    (each with its trailing blank line), so --write can always fix what --check reports. If
    not, inserts it after the "# " title ("# Title" / blank / "> Status: ..." / blank,
    matching the sibling files), or at the top of the file when it has no title. Fenced
    examples and "> Status:" callouts in body sections are never touched.
    Returns True if the file was actually changed, False otherwise.
    """
    if not file_path.exists():
        return False

    content = file_path.read_text()
    generated_line = _generate_status_line(domain_or_package, status_text)
    if not generated_line:
        return False

    lines = content.splitlines(keepends=True)
    status_indices, heading_index = _scan_header(lines)

    if status_indices:
        first, duplicates = status_indices[0], status_indices[1:]
        generic_suffix = _extract_generic_suffix(lines[first])
        new_line = generated_line + (" " + generic_suffix if generic_suffix else "") + "\n"
        # Only mark as changed if the line actually differs
        if lines[first] == new_line and not duplicates:
            return False
        lines[first] = new_line
        # Drop later header duplicates bottom-up so earlier indices stay valid. Take the blank
        # line after each one, or the blank before it when it ends the file, to keep the layout.
        for i in reversed(duplicates):
            if i + 1 < len(lines) and not lines[i + 1].strip():
                del lines[i:i + 2]
            elif i + 1 >= len(lines) and i - 1 > first and not lines[i - 1].strip():
                del lines[i - 1:i + 1]
            else:
                del lines[i]
    else:
        # Insert after the "# " title, or at index 0 when there is none. If the title is the
        # last line (a one-line stub), this appends after it.
        at = 0 if heading_index is None else heading_index + 1
        if at > 0 and not lines[at - 1].endswith("\n"):
            lines[at - 1] += "\n"
        block = ([] if at == 0 else ["\n"]) + [generated_line + "\n"]
        if at < len(lines) and lines[at].strip():
            block.append("\n")
        lines[at:at] = block

    file_path.write_text("".join(lines))
    return True


def _status_line_problem(path: Path, key: str, status_text: dict[str, str]) -> str:
    """Why a README/glossary header status line is out of sync with STATUS.md, or "" if fine."""
    expected_line = _generate_status_line(key, status_text)
    # A missing README/glossary is not this check's concern: file presence is a separate MUST gate.
    if not expected_line or not path.exists():
        return ""
    all_lines = path.read_text().splitlines()
    status_indices, _ = _scan_header(all_lines)
    lines = [all_lines[i] for i in status_indices]
    if not lines:
        return "missing status line"
    if len(lines) > 1:
        return f"{len(lines)} status lines (expected exactly one)"
    current = lines[0].strip()
    suffix = _extract_generic_suffix(current)
    expected = expected_line + (" " + suffix if suffix else "")
    return "" if current == expected.strip() else "stale status line"


