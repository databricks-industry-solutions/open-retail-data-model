def validate_self_review(status: dict[str, str], reviewers: dict[str, tuple[str, str]],
                         owners: dict[str, str], exempt: frozenset[str] = frozenset()) -> list[str]:
    """✅ rows whose Owner is also the Reviewer but that record only one sign-off (empty = ok).

    GOVERNANCE.md: a self-reviewed deliverable (Owner = Reviewer) can reach 🟢 on its own
    sign-off, but ✅ Published needs a second, independent reviewer's sign-off, recorded as a
    second reference in the Sign-off cell ("#165, #170"). This checks the count, not who signed.
    """
    names = dict(CORE_LAYOUT) | {k: n for _, rows in OUTCOME_LAYOUT for k, n, _ in rows}
    problems = []
    for key, emoji in status.items():
        if emoji != "✅" or key in exempt:
            continue
        name = names.get(key, key)
        if name not in reviewers:
            continue
        reviewer, signoff = reviewers[name]
        shared = _handles(owners.get(name, "")) & _handles(reviewer)
        refs = _signoff_refs(signoff) or []
        if shared and len(set(refs)) < 2:
            problems.append(f"{key} is ✅ in STATUS.md but is self-reviewed in REVIEWERS.md for "
                            f"{name!r} (Owner and Reviewer both {', '.join(sorted(shared))}) with "
                            f"{len(set(refs))} sign-off; add the second, independent reviewer's "
                            "sign-off to the Sign-off cell as '#A, #B' (GOVERNANCE.md)")
    return problems


def render_all(text: str, status: dict[str, str]) -> str:
    text = _replace_block(text, BADGE_START, BADGE_END, render_badge(status), pad=False)
    text = _replace_block(text, CORE_START, CORE_END, render_core_table(status))
    text = _replace_block(text, OUTCOME_START, OUTCOME_END, render_outcome_tables(status))
    return text


def collect_check_problems(status: dict[str, str], status_text_map: dict[str, str],
                           readme_text: str, reviewers_text: str) -> list[tuple[str, list[str]]]:
    """Every --check problem as (heading, items) sections; empty = in sync.

    Runs all the validators (layout, README surfaces, per-folder status lines, sign-offs)
    so one run reports everything, rather than stopping at the first failing one.
    """
    sections: list[tuple[str, list[str]]] = []

    layout = validate_layout(status)
    if layout:
        sections.append(("STATUS.md and tools/gen_status.py LAYOUT disagree:", layout))

    expected = {
        "status badge": (BADGE_START, BADGE_END, render_badge(status)),
        "canonical-core status table": (CORE_START, CORE_END, render_core_table(status)),
        "outcome-package status tables": (OUTCOME_START, OUTCOME_END, render_outcome_tables(status)),
    }
    stale = [label for label, (s, e, block) in expected.items()
             if _current_block(readme_text, s, e).strip() != block.strip()]
    if stale:
        sections.append(("README status surfaces are stale. Run: python tools/gen_status.py --write",
                         stale))

    stale_files = []
    targets = [("canonical-core", key) for key, _ in CORE_LAYOUT]
    targets += [("outcome-packages", pkg_key) for _, rows in OUTCOME_LAYOUT for pkg_key, _, _ in rows]
    for layer, key in targets:
        for name in ("README.md", "glossary.md"):
            path = REPO_ROOT / layer / key / name
            problem = _status_line_problem(path, key, status_text_map)
            if problem:
                stale_files.append(f"{path.relative_to(REPO_ROOT)}: {problem}")
    if stale_files:
        sections.append((f"Missing, duplicated or stale status lines in {len(stale_files)} files. "
                         "Edit STATUS.md, then run: python tools/gen_status.py --write", stale_files))

    stale_layer = [f"{path.relative_to(REPO_ROOT)}: {key}" for path in LAYER_READMES
                   for key in _sync_layer_table(path.read_text(), status_text_map)[1]]
    if stale_layer:
        sections.append(("Layer README status cells disagree with STATUS.md. "
                         "Run: python tools/gen_status.py --write", stale_layer))

    unsigned = validate_signoffs(status, parse_reviewers(reviewers_text))
    if unsigned:
        sections.append(("Review-complete rows in STATUS.md need a recorded sign-off in REVIEWERS.md: "
                         "an assigned Reviewer plus a Sign-off linking the review-signoff issue "
                         "(docs/definition-of-done.md). Record the sign-off or lower the status:",
                         unsigned))
    self_reviewed = [] if INITIAL_PUBLICATION_SELF_REVIEW else validate_self_review(
        status, parse_reviewers(reviewers_text), parse_owners(reviewers_text),
        exempt=self_review_exempt())
    if self_reviewed:
        sections.append(("Self-reviewed rows need a second, independent sign-off before ✅ Published "
                         "(GOVERNANCE.md). Record it in REVIEWERS.md or lower the status:",
                         self_reviewed))
    return sections


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if a README block is stale")
    ap.add_argument("--write", action="store_true", help="regenerate the blocks in the README")
    args = ap.parse_args(argv)

    status_text_map = parse_status_text(STATUS_PATH.read_text())
    status = parse_status(STATUS_PATH.read_text())
    text = README_PATH.read_text()

    if args.check:
        sections = collect_check_problems(status, status_text_map, text, REVIEWERS_PATH.read_text())
        for heading, items in sections:
            print(heading)
            for item in items:
                print(f"  - {item}")
        if sections:
            return 1
        print("README status surfaces and domain/package status lines are in sync with STATUS.md.")
        return 0

    problems = validate_layout(status)
    if problems:
        print("STATUS.md and tools/gen_status.py LAYOUT disagree:")
        for p in problems:
            print(f"  - {p}")
        return 1

    if args.write:
        README_PATH.write_text(render_all(text, status))
        print(f"Wrote status badge + tables to {README_PATH}")

        # Update domain/package README and glossary status lines
        dr_count = generate_domain_readme_status(status_text_map)
        dg_count = generate_domain_glossary_status(status_text_map)
        pr_count = generate_package_readme_status(status_text_map)
        pg_count = generate_package_glossary_status(status_text_map)
        layer_count = generate_layer_readme_status(status_text_map)
        total_updated = dr_count + dg_count + pr_count + pg_count + layer_count
        if total_updated:
            print(f"Updated {total_updated} domain/package status lines")
        return 0

    print(render_badge(status))
    print()
    print(render_core_table(status))
    print()
    print(render_outcome_tables(status))
    return 0


if __name__ == "__main__":
    sys.exit(main())
