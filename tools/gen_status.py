# The layer READMEs carry a hand-laid-out table with a Status cell per row. --write refreshes that
# cell from STATUS.md and --check reports a stale one, so the layer pages cannot drift from it.
LAYER_READMES = (REPO_ROOT / "canonical-core" / "README.md", REPO_ROOT / "outcome-packages" / "README.md")
_LAYER_HEADER = re.compile(r"^\|[^|]*\|\s*Status\s*\|")
_LAYER_ROW = re.compile(r"^(\|\s*\[[^\]]*\]\(([a-z0-9-]+)/\)\s*\|)([^|]*)(\|.*)$")


def _sync_layer_table(text: str, status_text: dict[str, str]) -> tuple[str, list[str]]:
    """Return text with each row's Status cell (the one after the linked name) set from
    STATUS.md, plus the keys that changed. Only rows of a table whose header's second column
    is Status are touched. A column-aligned cell (padded with more than one
    space) keeps its width where the new text fits."""
    out, stale, in_status_table = [], [], False
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\n")
        if not body.startswith("|"):
            in_status_table = False
        elif not in_status_table and _LAYER_HEADER.match(body):
            in_status_table = True
        m = _LAYER_ROW.match(body) if in_status_table else None
        if m and m.group(2) in status_text and m.group(3).strip() != status_text[m.group(2)]:
            width = len(m.group(3)) if m.group(3).endswith("  ") else 0
            cell = f" {status_text[m.group(2)]} ".ljust(width)
            line = m.group(1) + cell + m.group(4) + line[len(body):]
            stale.append(m.group(2))
        out.append(line)
    return "".join(out), stale


def generate_layer_readme_status(status_text: dict[str, str]) -> int:
    """Refresh the Status cells in canonical-core/README.md and outcome-packages/README.md.

    Returns number of files changed.
    """
    count = 0
    for path in LAYER_READMES:
        new_text, stale = _sync_layer_table(path.read_text(), status_text)
        if stale:
            path.write_text(new_text)
            count += 1
    return count


def validate_layout(status: dict[str, str]) -> list[str]:
    """Return a list of drift problems between STATUS.md and LAYOUT (empty = ok)."""
    problems = []
    layout_keys = {k for k, _ in CORE_LAYOUT} | {
        k for _, rows in OUTCOME_LAYOUT for k, _, _ in rows
    }
    for k in layout_keys - set(status):
        problems.append(f"LAYOUT lists {k!r} but STATUS.md has no such row")
    for k in set(status) - layout_keys:
        problems.append(f"STATUS.md has row {k!r} not in tools/gen_status.py LAYOUT")
    return problems


# A recorded sign-off is a reference to the review-signoff issue (or PR) in REVIEWERS.md's
# Sign-off column, and nothing else: a bare "#147", or a link whose text and target name the
# same number, "[#147](https://github.com/databricks-industry-solutions/open-retail-data-model/issues/147)" (or .../pull/147),
# pinned to this repo. The check validates the FORM of the reference, not the issue's verdict.
SIGNOFF_CELL = re.compile(
    r"#(?P<bare>\d+)"
    r"|\[#(?P<text>\d+)\]\(https://github\.com/databricks-industry-solutions/open-retail-data-model/(?:issues|pull)/(?P<target>\d+)\)"
)
SIGNOFF_FORMAT = "#NNN or [#NNN](https://github.com/databricks-industry-solutions/open-retail-data-model/issues/NNN)"


def _is_signoff_ref(cell: str) -> bool:
    """True if a Sign-off cell is exactly one issue/PR reference (see SIGNOFF_CELL)."""
    m = SIGNOFF_CELL.fullmatch(cell.strip())
    return bool(m) and (m["bare"] is not None or m["text"] == m["target"])


def _signoff_refs(cell: str) -> list[str] | None:
    """The issue/PR numbers in a Sign-off cell: one reference, or several separated by commas
    (a self-reviewed deliverable records its second sign-off this way). None if any part is
    not a valid reference (see SIGNOFF_CELL)."""
    parts = [p.strip() for p in cell.split(",")]
    if not parts or not all(_is_signoff_ref(p) for p in parts):
        return None
    return [SIGNOFF_CELL.fullmatch(p)["bare"] or SIGNOFF_CELL.fullmatch(p)["text"] for p in parts]


def _handles(cell: str) -> set[str]:
    """The @handles named in an Owner/Reviewer cell, lower-cased."""
    return {h.lower() for h in re.findall(r"@[A-Za-z0-9-]+", cell)}


def parse_owners(text: str) -> dict[str, str]:
    """Map each REVIEWERS.md row's display name (first column) -> its Owner cell (second column)."""
    out: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3:
            continue
        name = cells[0]
        if name.lower() in ("entity", "outcome package") or set(name) <= set("-: "):
            continue
        out[name] = cells[1]
    return out


def parse_reviewers(text: str) -> dict[str, tuple[str, str]]:
    """Map each REVIEWERS.md row's display name (first column) -> (Reviewer, Sign-off).

    Reviewer is the third column and Sign-off the fourth ("" when a row has no fourth cell).
    """
    out: dict[str, tuple[str, str]] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3:
            continue
        name = cells[0]
        # skip header + separator rows
        if name.lower() in ("entity", "outcome package") or set(name) <= set("-: "):
            continue
        out[name] = (cells[2], cells[3] if len(cells) > 3 else "")
    return out


def validate_signoffs(status: dict[str, str], reviewers: dict[str, tuple[str, str]]) -> list[str]:
    """Review-complete rows in STATUS.md without a recorded sign-off in REVIEWERS.md (empty = ok).

    docs/definition-of-done.md: 🟢 (and so ✅) is a merge plus a recorded sign-off by the
    assigned reviewer. So each such row needs an assigned Reviewer AND a Sign-off that links
    the review-signoff issue (#NNN); being listed as Reviewer alone is not a sign-off. 🔵 and
    below need neither. STATUS.md keys rows by folder name and REVIEWERS.md by display name;
    LAYOUT maps one to the other.
    """
    names = dict(CORE_LAYOUT) | {k: n for _, rows in OUTCOME_LAYOUT for k, n, _ in rows}
    problems = []
    for key, emoji in status.items():
        if emoji not in DONE_EMOJI:
            continue
        name = names.get(key, key)
        if name not in reviewers:
            problems.append(f"{key} is {emoji} in STATUS.md but REVIEWERS.md has no {name!r} row")
            continue
        reviewer, signoff = reviewers[name]
        if not reviewer.strip("—- "):
            problems.append(f"{key} is {emoji} in STATUS.md but has no assigned reviewer in "
                            f"REVIEWERS.md for {name!r} (Reviewer is {reviewer or 'empty'!r})")
        if not signoff.strip("—- "):
            problems.append(f"{key} is {emoji} in STATUS.md but has no recorded sign-off in "
                            f"REVIEWERS.md for {name!r} (Sign-off is {signoff or 'empty'!r}; "
                            "link the review-signoff issue, e.g. #123)")
        elif _signoff_refs(signoff) is None:
            problems.append(f"{key} is {emoji} in STATUS.md but its REVIEWERS.md Sign-off for "
                            f"{name!r} is not an issue/PR reference ({signoff!r}; expected "
                            f"{SIGNOFF_FORMAT})")
    return problems


